-- Schema as originally created by Hibernate's ddl-auto=update.
-- IF NOT EXISTS lets this run safely on databases that already have these tables.

CREATE TABLE IF NOT EXISTS repository_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6),
    last_scanned_at TIMESTAMP(6),
    name VARCHAR(255) NOT NULL,
    status VARCHAR(255),
    url VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS webhook_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commit_sha VARCHAR(255),
    event_type VARCHAR(255),
    payload TEXT,
    received_at TIMESTAMP(6),
    repository_name VARCHAR(255),
    status VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS drift_report (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analyzed_at TIMESTAMP(6),
    commit_sha VARCHAR(255),
    repository_name VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS drift_suggestion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confidence_score DOUBLE PRECISION,
    drift_type VARCHAR(255),
    endpoint_path VARCHAR(255),
    file_path VARCHAR(255),
    http_method VARCHAR(255),
    impacted_symbol VARCHAR(255),
    is_breaking_change BOOLEAN,
    old_text TEXT,
    reason TEXT,
    schema_format VARCHAR(255),
    severity VARCHAR(255),
    status VARCHAR(255),
    suggested_text TEXT,
    report_id BIGINT REFERENCES drift_report (id)
);
